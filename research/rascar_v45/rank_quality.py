class Dense(nn.Module):
    def __init__(self):super().__init__();self.net=nn.Conv2d(384,4,1)
    def forward(self,x):return self.net(F.normalize(x,dim=1)*np.sqrt(384))

def feature_row(r,cb,prob,heads,hands):
    cls=r.class_name;box=r[B].to_numpy(float);size=cb[2:]-cb[:2];k=CL.index(cls);p=prob[k]
    yy,xx=np.mgrid[:32,:32];x=cb[0]+(xx+.5)*size[0]/32;y=cb[1]+(yy+.5)*size[1]/32
    inside=(x>=box[0])&(x<=box[2])&(y>=box[1])&(y<=box[3]);f={f'class_{c}':float(cls==c) for c in CL}
    f.update(confidence=r.confidence,logw=np.log(max(box[2]-box[0],1)),logh=np.log(max(box[3]-box[1],1)),cx=(box[0]+box[2])/2560,cy=(box[1]+box[3])/1440,mask_mean=float(p[inside].mean()),mask_max=float(p[inside].max()),mask_coverage=float((p[inside]>=.5).mean()))
    for c in range(4):f[f'class_prob_{c}']=float(prob[c][inside].mean())
    bb,pp,conf=anchors(r.frame_id,cls,heads,hands) if cls in ['person','nude_hands'] else (np.empty((0,4)),np.empty((0,2)),np.empty(0))
    n,labels,stats,_=cv2.connectedComponentsWithStats((p>=.5).astype(np.uint8),8);refs=[]
    for s in stats[1:]:
        xx0,yy0,w,hh,area=s
        if area>=4:refs.append(np.array([xx0,yy0,xx0+w,yy0+hh])/32*np.tile(size,2)+np.tile(cb[:2],2))
    ov=np.nan;oldbox=np.full(4,np.nan)
    if refs:
        o=iou(box,refs)[0];j=o.argmax();ov=o[j];oldbox=refs[j]
    f.update(dense_iou=0. if not np.isfinite(ov) else ov,dense_missing=float(not len(refs)),components=len(refs),anchors_in_query=int((((pp>=box[:2])&(pp<=box[2:])).all(1)).sum()))
    f['anchors_in_reference']=int((((pp>=oldbox[:2])&(pp<=oldbox[2:])).all(1)).sum())
    f['external_iou']=float(iou(box,bb).max()) if len(bb) else 0.;f['external_conf']=float(conf[np.argmax(iou(box,bb)[0])]) if len(bb) else 0.
    new=split_map(p,cb,bb,pp,'voronoi');f['split_iou']=max([float(iou(box,z[0])[0,0]) for z in new],default=0.)
    for i,c in enumerate(B):f[f'dense_delta_{c}']=float((oldbox[i]-box[i])/max((box[2:]-box[:2])[i%2],1)) if refs else 0.
    return f,ov

def main():
    q,te,h=inputs();bo,bt=baseline(q,te);bq,bte=v22base(q,te);rec=pd.read_csv(ROOT/'rascar_v31/inputs/dense_records.csv');lookup=rec.reset_index().set_index('id')['index'].to_dict()
    feat=np.load(ROOT/'rascar_v31/features/dense_grids.npy',mmap_mode='r');targets=np.load(ROOT/'rascar_v31/features/dense_targets.npy',mmap_mode='r');heads=load_jsonl('head');hands=load_jsonl('hand_local');all_features=[];manifest=[]
    for fit in DAYS:
        fitting=q[q.day.eq(fit)];frames=sorted(fitting.frame_id.unique());parts=np.array_split(frames,3);train_manual=rec[rec.split.eq('manual')&rec.day.eq(fit)]
        for fold,held in enumerate(parts):
            # All crops of held frames are excluded; purge +/-120-second context too.
            times=pd.to_datetime(train_manual.frame_id.str.extract(r'(\d{8}_\d{6})$')[0],format='%Y%m%d_%H%M%S').astype('int64').to_numpy()/1e9
            ht=np.array([pd.to_datetime(s[-15:],format='%Y%m%d_%H%M%S').timestamp() for s in held]);ix=train_manual.index[(np.abs(times[:,None]-ht[None])>120).all(1)].to_numpy()
            assert not set(rec.iloc[ix].frame_id)&set(held)
            torch.manual_seed(3101);rng=np.random.default_rng(3101);model=Dense();opt=torch.optim.AdamW(model.parameters(),lr=.0007,weight_decay=.01);n=rec.iloc[ix].groupby('frame_id').size();weights=np.array([1/n[f] for f in rec.frame_id.iloc[ix]]);weights/=weights.sum()
            for step in range(450):
                sample=rng.choice(ix,8,replace=True,p=weights);z=model(torch.from_numpy(np.array(feat[sample],np.float32)));y=torch.from_numpy(np.array(targets[sample],np.float32));loss=F.binary_cross_entropy_with_logits(z,y,weight=1+3*y);opt.zero_grad();loss.backward();nn.utils.clip_grad_norm_(model.parameters(),5);opt.step()
            torch.save(model.state_dict(),A/f'models/inner_dense_fit{fit[-2:]}_block{fold}.pt');model.eval();manifest.append(dict(outer_fit_day=fit,inner_block=fold,fit_frames=sorted(rec.iloc[ix].frame_id.unique()),held_frames=list(held)))
            for _,r in fitting[fitting.frame_id.isin(held)].iterrows():
                i=lookup[r.id]
                with torch.inference_mode():prob=model(torch.from_numpy(np.array(feat[i:i+1],np.float32)))[0].sigmoid().numpy()
                f,ov=feature_row(r,rec.loc[i,CB].to_numpy(float),prob,heads,hands);all_features.append(dict(id=r.id,outer_fit_day=fit,role='meta_train',day=r.day,frame_id=r.frame_id,class_name=r.class_name,error=r.error,overlap=ov,**f))
            print('INNER',fit,fold,'frames',len(set(rec.iloc[ix].frame_id)),flush=True)
        data=np.load(ROOT/f'rascar_v31/features/linear_mask_fit{fit[-2:]}_maps.npz');ml={s:i for i,s in enumerate(data['ids'])}
        for role,rows in [('oof',q[q.day.ne(fit)]),('test',te)]:
            for _,r in rows.iterrows():
                i=lookup[r.id];f,ov=feature_row(r,rec.loc[i,CB].to_numpy(float),data['maps'][ml[r.id]].astype(float),heads,hands)
                all_features.append(dict(id=r.id,outer_fit_day=fit,role=role,day=r.day,frame_id=r.frame_id,class_name=r.class_name,error=r.get('error',np.nan),overlap=ov,**f))
    features=pd.DataFrame(all_features);features.to_csv(A/'features/nested_quality.csv',index=False);(A/'models/nested_manifest.json').write_text(json.dumps(manifest,indent=2))
    columns=[c for c in features if c not in ['id','outer_fit_day','role','day','frame_id','class_name','error','overlap']];results=[];predictions=[]
    for fit in DAYS:
        tr=features[features.outer_fit_day.eq(fit)&features.role.eq('meta_train')];ev=features[features.outer_fit_day.eq(fit)&features.role.ne('meta_train')];scale=StandardScaler().fit(tr[columns]);x=scale.transform(tr[columns]);xx=scale.transform(ev[columns]);y=tr.error.to_numpy()
        for kind in ['logreg','cross_class_rank']:
            if kind=='logreg':
                model=LogisticRegression(C=.1,max_iter=1000).fit(x,y);pred=model.predict_proba(xx)[:,1];joblib.dump((columns,scale,model),A/f'models/{kind}_fit{fit[-2:]}.joblib')
            else:
                torch.manual_seed(4503);model=nn.Linear(x.shape[1],1);nn.init.zeros_(model.weight);nn.init.zeros_(model.bias);opt=torch.optim.AdamW(model.parameters(),lr=.02,weight_decay=0.)
                xt=torch.tensor(x,dtype=torch.float32);yt=torch.tensor(y,dtype=torch.float32);p=np.flatnonzero(y==1);n=np.flatnonzero(y==0)
                for step in range(500):
                    z=model(xt)[:,0];pair=F.softplus(-(z[p,None]-z[None,n])).mean();loss=F.binary_cross_entropy_with_logits(z,yt)+.5*pair+.15*model.weight.square().sum();opt.zero_grad();loss.backward();opt.step()
                with torch.inference_mode():pred=model(torch.tensor(xx,dtype=torch.float32))[:,0].sigmoid().numpy()
                joblib.dump((columns,scale),A/f'models/{kind}_scale_fit{fit[-2:]}.joblib');torch.save(model.state_dict(),A/f'models/{kind}_fit{fit[-2:]}.pt')
            predictions.append(ev[['id','role','outer_fit_day','day','frame_id','class_name','error','overlap']].assign(kind=kind,quality_error=pred))
    pred=pd.concat(predictions);pred.to_csv(A/'features/nested_predictions.csv',index=False)
    for kind in pred.kind.unique():
        p=pred[pred.kind.eq(kind)];oo=p[p.role.eq('oof')].set_index('id').loc[q.id];tt=[g.set_index('id').loc[te.id] for _,g in p[p.role.eq('test')].groupby('outer_fit_day')]
        for scope in ['all','person']:
            for weight in [.05,.10]:
                # Replace a fraction of the dense target with estimated error probability.
                o=bo.copy();t=bt.copy();oldtarget=np.clip((.85-oo.overlap.to_numpy())/.5,0,1);change=oo.quality_error.to_numpy()-oldtarget;ok=np.isfinite(change)
                if scope=='person':ok&=q.class_name.eq('person').to_numpy()
                o[ok]=np.clip(bo[ok]+weight*change[ok],0,1)
                changes=np.stack([g.quality_error.to_numpy()-np.clip((.85-g.overlap.to_numpy())/.5,0,1) for g in tt]);same=(changes>=0).all(0)|(changes<=0).all(0);ok=np.isfinite(changes).all(0)&same
                if scope=='person':ok&=te.class_name.eq('person').to_numpy()
                delta=np.where((changes>=0).all(0),np.min(changes,0),np.max(changes,0));t[ok]=np.clip(bt[ok]+weight*delta[ok],0,1)
                name=f'nested_{kind}_{scope}_w{int(weight*100):02}';q.assign(score=o).to_csv(A/f'results/oof/{name}.csv',index=False);te[['id']].assign(score=t).to_csv(A/f'results/submissions/{name}.csv',index=False)
                results.append(dict(name=name,**metrics(q,o),standalone_ap=AP(q.error,oo.quality_error),changed_oof=int((abs(o-bo)>1e-10).sum()),changed_test=int((abs(t-bt)>1e-10).sum())))
    pd.DataFrame(results).to_csv(A/'results/nested_experiments.csv',index=False);print(pd.DataFrame(results).to_string(index=False))
if __name__=='__main__':main()
